// Builds supabase/dashboard/analyze.single.ts — one file you can paste into the
// Supabase dashboard editor. Run: npm run build:dashboard-fn
const fs = require('fs');
const strip = (s) =>
  s.replace(/^import .*from '\.\.\/_shared\/.*';\n/gm, '')
   .replace(/^export (?=(async )?function|const|interface|type )/gm, '');
const read = (p) => fs.readFileSync(p, 'utf8');
const u = strip(read('supabase/functions/_shared/url-checks.ts'));
const p = strip(read('supabase/functions/_shared/prompt.ts'));
let i = read('supabase/functions/Analyze/index.ts');
const jsr = i.split('\n').find((l) => l.includes('jsr:@supabase'));
i = strip(i).replace(jsr + '\n', '');
fs.writeFileSync(
  'supabase/dashboard/analyze.single.ts',
  `// SINGLE-FILE VERSION for the Supabase dashboard editor (function name: Analyze).\n` +
    `// Generated by scripts/build-dashboard-function.js — edit supabase/functions/*, not this.\n` +
    `${jsr}\n\n// ---- url-checks ----\n${u}\n// ---- prompt ----\n${p}\n// ---- handler ----\n${i}`
);
console.log('wrote supabase/dashboard/analyze.single.ts');
